export const translatedQuotes = quoteCorpus.map((quote, index) => ({
  ...quote,
  translation: translations[index],
}))

const translationsByQuote = new Map(
  translatedQuotes.map(({ text, translation }) => [
    text
      .normalize('NFKC')
      .toLocaleLowerCase('en-US')
      .replace(/[^\p{L}\p{N}]+/gu, ' ')
      .trim(),
    translation,
  ]),
)

/**
 * @param {string} quoteText
 * @returns {string | null}
 */
export function findQuoteTranslation(quoteText) {
  const key = quoteText
    .normalize('NFKC')
    .toLocaleLowerCase('en-US')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()

  return translationsByQuote.get(key) ?? null
}

export function getRandomTranslatedQuote() {
  return translatedQuotes[Math.floor(Math.random() * translatedQuotes.length)]
}
